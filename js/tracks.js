// tracks.js - Race course definitions.
//
// Gate positions were laid out against the actual bando.glb collision mesh: every ring and
// every flown line between consecutive gates was checked for clearance before being committed
// here. Several gates sit inside openings only a couple of metres across, so a gate moved even
// half a metre is likely to end up buried in a wall, a panel or the first-floor slab. Re-measure
// before editing.
//
// `yaw` is the direction of travel through the gate, in degrees, measured the same way the
// drone's heading is: 0 looks down -Z (the way the airframe faces at spawn), +90 looks down +X.
// `pitch` tilts that direction out of the horizontal, +90 being straight up, so the normal is
// (sin(yaw)cos(pitch), sin(pitch), -cos(yaw)cos(pitch)). The ring is built perpendicular to it.
// Since a gate counts from either side, yaw and pitch now only decide how the ring hangs in the
// air, not which way it has to be flown: what matters is that the disc lies square across the
// opening it is threaded through. A gate lying flat in a floor hatch counts on the way up and on
// the way down alike, so the only thing keeping the two shaft gates apart is that a gate is armed
// only when the run has reached it.
//
// `radius` overrides the track default for a single gate. The rings threaded through the wall
// holes have to be smaller than the holes themselves.
//
// Rift Run is surveyed differently. `rift-quarry.glb` is generated by `tools/generate-rift-
// quarry.mjs`, and the racing line is defined in the same constants the geometry is built from,
// so its gates are computed rather than measured: each ring's yaw and pitch is the tangent of the
// flown line at that point, and the generator checks every ring and every leg against the
// finished triangles before it writes the file. The numbers below are that survey's output. Do
// not hand-edit them - change the layout in the generator and regenerate both.

